#!/usr/bin/env python3
"""Ghost ECC localization.

The Swift code uses Serbian (ijekavian, Latin) text as localization keys. This script
  1. extracts every localized literal from the app sources,
  2. checks that GhostECC/Localization/translations-en.json has an English value for each
     (with the same placeholders), and
  3. writes the .strings files: English translations, plus identity tables for Serbian
     (Latin and Cyrillic locale), Croatian and Bosnian, which all show the original text.

Run after changing UI text:  python3 scripts/l10n.py   (add --check to only verify)
"""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
APP = ROOT / 'GhostECC'
L10N = APP / 'Localization'
TRANSLATIONS = L10N / 'translations-en.json'
SERBIAN_FAMILY = ['sr-Latn', 'sr', 'hr', 'bs']

# Keys used outside Swift literals (APNs payload loc-key) with their Serbian text.
EXTRA = {'PUSH_NEW_MESSAGE': 'Nova poruka'}
# Info.plist strings, localized through InfoPlist.strings.
INFO_PLIST_EN = {
    'NSFaceIDUsageDescription': 'Unlock Ghost ECC.',
    'NSCameraUsageDescription': 'Scan the QR code of a Ghost invitation.',
    'NSMicrophoneUsageDescription': 'Record a voice message. The audio stays in memory only.',
}

CALLS = r'(?:\b(?:Text|Label|Button|Toggle|Section|TextField|SecureField|ContentUnavailableView|LabeledContent|Picker|ProgressView|LocalizedStringKey)\(|\.(?:navigationTitle|alert|confirmationDialog|accessibilityLabel|accessibilityHint)\(|\b(?:title|text):\s*|String\(localized:\s*)'
START = re.compile(CALLS + r'\s*"')


def parse_literal(src, i):
    """src[i] is the opening quote. Returns (key, end) with interpolations turned into %@."""
    assert src[i] == '"'
    i += 1
    out = []
    while i < len(src):
        c = src[i]
        if c == '"':
            return ''.join(out), i + 1
        if c == '\\':
            nxt = src[i + 1]
            if nxt == '(':
                depth, j = 1, i + 2
                while depth:
                    if src[j] == '(':
                        depth += 1
                    elif src[j] == ')':
                        depth -= 1
                    j += 1
                out.append('%@')
                i = j
                continue
            out.append({'n': '\n', 't': '\t', '"': '"', '\\': '\\'}.get(nxt, nxt))
            i += 2
            continue
        if c == '%':
            out.append('%%')
            i += 1
            continue
        out.append(c)
        i += 1
    raise ValueError('unterminated string literal')


def extract():
    keys = {}
    for path in sorted(APP.rglob('*.swift')):
        src = path.read_text()
        for match in START.finditer(src):
            key, _ = parse_literal(src, match.end() - 1)
            if key.strip():
                keys.setdefault(key, f'{path.relative_to(ROOT)}:{src[:match.start()].count(chr(10)) + 1}')
    return keys


def escape(value):
    return value.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')


def write_strings(path, pairs):
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = ['/* Generated by scripts/l10n.py. Edit translations-en.json, not this file. */']
    lines += [f'"{escape(k)}" = "{escape(v)}";' for k, v in pairs]
    path.write_text('\n'.join(lines) + '\n', encoding='utf-8')


def main():
    check_only = '--check' in sys.argv
    keys = extract()
    translations = json.loads(TRANSLATIONS.read_text()) if TRANSLATIONS.exists() else {}
    missing = [k for k in keys if k not in translations] + [k for k in EXTRA if k not in translations]
    unused = [k for k in translations if k not in keys and k not in EXTRA]
    bad = [k for k, v in translations.items() if (k in keys or k in EXTRA) and k.count('%@') != v.count('%@')]
    for k in missing:
        print(f'MISSING  {keys.get(k, "extra")}: {k!r}')
    for k in bad:
        print(f'PLACEHOLDER MISMATCH: {k!r}')
    for k in unused:
        print(f'unused translation: {k!r}')
    if missing or bad:
        sys.exit(1)
    ordered = sorted(keys) + sorted(EXTRA)
    if not check_only:
        write_strings(L10N / 'en.lproj' / 'Localizable.strings', [(k, translations[k]) for k in ordered])
        write_strings(L10N / 'en.lproj' / 'InfoPlist.strings', sorted(INFO_PLIST_EN.items()))
        for lang in SERBIAN_FAMILY:
            write_strings(L10N / f'{lang}.lproj' / 'Localizable.strings', [(k, EXTRA.get(k, k)) for k in ordered])
    print(f'{len(keys)} localized strings, English complete; tables {"checked" if check_only else "written"}.')


if __name__ == '__main__':
    main()
